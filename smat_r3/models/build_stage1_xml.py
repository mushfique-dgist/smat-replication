"""Writes smat_hipexo_26_stage1.xml: the device model smat_hipexo_26.xml with the three exo bodies
(exo_pack, exo_hip_pod_r, exo_hip_pod_l; 5.94 kg in total) removed and the two exo actuators kept, so the
Stage-1 human trains without the device mass and with the same 28-dim action space (D-XML-06).
Run from this directory after build_hipexo_xml.py."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
xml = open(os.path.join(HERE, "smat_hipexo_26.xml"), encoding="utf-8").read()
pat = re.compile(r'[ \t]*<!-- SMAT_R3 D-XML-01[^\n]*\n[ \t]*<body name="exo_(?:pack|hip_pod_r|hip_pod_l)"[^>]*>\s*<geom[^>]*/>\s*</body>\n', re.S)
xml1, n = pat.subn("", xml)
assert n == 3, n
assert "exo_pack" not in xml1 and "exo_hip_pod" not in xml1 and 'name="Exo_R"' in xml1 and 'name="Exo_L"' in xml1
xml1 = xml1.replace("<mujoco", "<!-- SMAT_R3 D-XML-06: Stage-1 variant of smat_hipexo_26.xml with the three exo bodies (5.94 kg) removed; "
                    "actuators kept so the action space is identical. Generated by build_stage1_xml.py; do not edit by hand. -->\n<mujoco", 1)
with open(os.path.join(HERE, "smat_hipexo_26_stage1.xml"), "w", encoding="utf-8", newline="\n") as f:
    f.write(xml1)
print("wrote smat_hipexo_26_stage1.xml")
